function detectLocale() {
  if (typeof window === "undefined") return "en";
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && locales[stored]) return stored;
  } catch {
    // ignore
  }

  // Default to English unless the user explicitly selected another locale.
  return "en";
}

let lang = detectLocale();
const localeListeners = new Set();

export function getLocale() {
  return lang;
}

export function subscribeLocaleChange(handler) {
  localeListeners.add(handler);
  return () => localeListeners.delete(handler);
}

export function setLocale(l) {
  if (!locales[l]) return;
  lang = l;
  try {
    localStorage.setItem(STORAGE_KEY, l);
  } catch {
    // ignore
  }
  localeListeners.forEach((handler) => {
    try {
      handler(lang);
    } catch {
      // ignore listener errors
    }
  });
}

export function useLocale() {
  const [locale, setLocaleState] = useState(getLocale());
  useEffect(() => subscribeLocaleChange(setLocaleState), []);
  return locale;
}

export function t(key) {
  return locales[lang]?.[key] || locales.en?.[key] || key;
}

